"""Generate docs/PRESETS.md from the shipped presets.  Run:  python tools/gen_preset_docs.py"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from atmosfx.core import physics  # noqa: E402
from atmosfx.core import presets as P  # noqa: E402


def row(p: P.Preset) -> str:
    sun = f"{p.sun.elevation_deg:+.1f}\u00b0"
    clouds = ", ".join(f"{c.kind.title()} {c.coverage:.0%}" for c in p.clouds) or "none"
    if p.deck.enabled:
        clouds += (", " if p.clouds else "") + f"2D deck {p.deck.coverage:.0%}"
    if p.fog.enabled:
        fog = f"{physics.visibility_class(p.fog.visibility_m)} {p.fog.visibility_m / 1000:g} km" if p.fog.mode != "DOMAIN" else "domain"
        if p.fog.mode in ("DOMAIN", "BOTH"):
            fog += f" + bank {p.fog.domain_visibility_m:g} m"
    else:
        fog = "off"
    sky = "stars" if p.stars.enabled else "-"
    if p.moon.enabled and p.stars.enabled:
        sky += f", moon {p.moon.phase:.0%}"
    return f"| **{p.name}** (`{p.id}`) | {sun} | {clouds} | {fog} | {sky} | {p.description} |"


def main() -> int:
    lines = ["# Preset library", "",
             "_Generated by `tools/gen_preset_docs.py` from `atmosfx/data/presets.json`. Do not edit by hand._", "",
             f"{len(P.library())} presets. Sun elevation is for Artistic mode; presets with a local hour also set it "
             "when you use Earth mode. 'Moon n%' is the Artistic-mode phase (0% new, 50% full).", ""]
    for cat, plist in P.by_category().items():
        if not plist:
            continue
        lines += [f"## {cat}", "", "| Preset | Sun | Clouds | Fog / haze | Night sky | Description |", "|---|---|---|---|---|---|"]
        lines += [row(p) for p in plist]
        lines.append("")
    out = os.path.join(ROOT, "docs", "PRESETS.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote", os.path.relpath(out, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
